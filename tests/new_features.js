'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const {lockText,unlockText,seal}=require('../note-security');
const {migrateLegacy,cleanTransients}=require('../storage-tools');
const {textNotes,pdfHtml,cmpVersion}=require('../note-formats');
const {readLegacy}=require('../sticky-import');
const B=require('../backup-tools');
const message='Super private **meeting** notes: '+ 'x'.repeat(1000);
const {vault,key}=lockText(message,'good_password_123');
assert.equal(vault.v,1);assert(!JSON.stringify(vault).includes('Super private'),'sealed notes contain ciphertext only');
assert.equal(unlockText(vault,'good_password_123').text,message);
assert.throws(()=>unlockText(vault,'bad_password'),/Incorrect password/);
assert.notEqual(seal(message,key,Buffer.from(vault.salt,'base64')).ct,vault.ct,'fresh nonce on every encrypted save');
const snapshot=B.snapshot({tabs:[{id:'t1',title:'Locked',text:message,vault}],folders:[],settings:{}});
assert(!JSON.stringify(snapshot).includes('Super private'));
const restored=B.restoreSnapshot(snapshot,{});assert(restored.tabs[0].vault?.ct);assert.equal(restored.tabs[0].text,'');
assert.equal(textNotes('MyNote.md','# Title')[0].title,'MyNote');
assert.equal(cmpVersion('v2.1.3','2.1.0'),1);assert.equal(cmpVersion('2.0.9','2.1.0'),-1);
let html=pdfHtml('<script>alert(1)</script>','# Heading\n**bold** and <script>bad</script>');
assert(!html.includes('<script>'),'exported HTML is escaped');assert(html.includes('<strong>bold</strong>'));
assert.deepEqual(readLegacy(path.join(__dirname,'fixtures/windows-sticky-demo.sqlite')).map(n=>n.text),['Demo sticky note from Windows']);
const root=fs.mkdtempSync(path.join(os.tmpdir(),'overnote-migrate-')),old=path.join(root,'sticky-notes'),newer=path.join(root,'Overnote');
fs.mkdirSync(old);fs.writeFileSync(path.join(old,'notes.json'),'LEGACY');fs.writeFileSync(path.join(old,'backup-credentials.enc'),'CREDENTIALS');
fs.mkdirSync(path.join(old,'backups'));fs.writeFileSync(path.join(old,'backups','overnote-2026-10-14T10-00-00-000Z.json'),'BACKUP');
const result=migrateLegacy(old,newer);assert(result.migrated.includes('notes.json'));
assert.equal(fs.readFileSync(path.join(newer,'notes.json'),'utf8'),'LEGACY');assert.equal(fs.readFileSync(path.join(old,'notes.json'),'utf8'),'LEGACY');
assert.equal(fs.readFileSync(path.join(newer,'backup-credentials.enc'),'utf8'),'CREDENTIALS');
assert(fs.existsSync(path.join(newer,'backups','overnote-2026-10-14T10-00-00-000Z.json')));
fs.writeFileSync(path.join(newer,'notes.json'),'NEW DATA');assert.deepEqual(migrateLegacy(old,newer).migrated,[]);assert.equal(fs.readFileSync(path.join(newer,'notes.json'),'utf8'),'NEW DATA');
fs.writeFileSync(path.join(newer,'tray-error.log'),'not private');cleanTransients(newer);assert(!fs.existsSync(path.join(newer,'tray-error.log')));
fs.rmSync(root,{recursive:true,force:true});
const idle=require('../idle-lock');
assert.deepEqual(idle.ALLOWED,[0,1,5,15,30,60]);
assert.equal(idle.normalizeMinutes('15'),15);
assert.equal(idle.normalizeMinutes('abc'),0);
assert.equal(idle.normalizeMinutes(999),0);
assert.equal(idle.shouldLock(0,Infinity,1),false);
assert.equal(idle.shouldLock(1,59000,1),false);
assert.equal(idle.shouldLock(1,60000,1),true);
assert.equal(idle.shouldLock(15,15*60000,0),false);
assert.equal(idle.shouldLock(15,15*60000,2),true);
console.log('New-feature tests passed: encrypted notes, wrong passwords, secure backups, migration, SQLite import, Markdown/PDF HTML, version compare and inactivity lock policy.');
