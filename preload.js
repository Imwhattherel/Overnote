const { contextBridge, ipcRenderer: ipc } = require('electron');
contextBridge.exposeInMainWorld('api', {
  load: () => ipc.invoke('load'),
  lockNote: (id,pass) => ipc.invoke('note-lock',id,pass),
  unlockNote: (id,pass) => ipc.invoke('note-unlock',id,pass),
  relockNote: id => ipc.invoke('note-relock',id),
  removeNoteLock: (id,pass) => ipc.invoke('note-remove-lock',id,pass),
  checkVersion: () => ipc.invoke('version-check'),
  cleanStorage: () => ipc.invoke('storage-clean'),
  exportFile: (id,format) => ipc.invoke('note-export-file',id,format),
  displays: () => ipc.invoke('displays'),
  currentDisplay: () => ipc.invoke('current-display'),
  moveToDisplay: id => ipc.invoke('move-to-display', id),
  getStartup: () => ipc.invoke('get-startup'),
  getAlarmSoundInfo: () => ipc.invoke('get-alarm-sound-info'),
  getAlarmAudio: () => ipc.invoke('get-alarm-audio'),
  chooseAlarmSound: () => ipc.invoke('choose-alarm-sound'),
  resetAlarmSound: () => ipc.invoke('reset-alarm-sound'),
  setStartup: enabled => ipc.invoke('set-startup', enabled),
  setReminder: (id, at, repeat, content, reminderId, important) => ipc.invoke('set-reminder', id, at, repeat, content, reminderId, important),
  reminderAction: (id, reminderId, action, minutes) => ipc.invoke('reminder-action', id, reminderId, action, minutes),
  search: query => ipc.invoke('search-notes', query),
  openNote: (id, query) => ipc.invoke('open-note', id, query),
  onFocusMatch: cb => ipc.on('focus-match', (_e, payload) => cb(payload)),
  onDockHover: cb => ipc.on('dock-hover', (_e, value) => cb(value)),
  update: (id, patch) => ipc.send('update', id, patch),
  setActive: id => ipc.send('set-active', id),
  add: folderId => ipc.invoke('add-note', folderId),
  folderColor: (id, color) => ipc.invoke('folder-color', id, color),
  favoriteColor: (color, add) => ipc.invoke('favorite-color', color, add),
  pinNote: (id, pinned) => ipc.invoke('pin-note', id, pinned),
  listTrash: () => ipc.invoke('list-trash'),
  restoreTrash: id => ipc.invoke('restore-trash', id),
  purgeTrash: id => ipc.invoke('purge-trash', id),
  exportNotes: (ids, withReminders) => ipc.invoke('notes-export', ids, withReminders),
  importNotes: () => ipc.invoke('notes-import'),
  backupSettings: () => ipc.invoke('backup-settings'),
  configureBackup: settings => ipc.invoke('backup-configure', settings),
  chooseBackupLocal: () => ipc.invoke('backup-pick-local'),
  resetBackupLocal: () => ipc.invoke('backup-reset-local'),
  backupNow: () => ipc.invoke('backup-now'),
  openBackupFolder: () => ipc.invoke('backup-open-folder'),
  restoreBackup: () => ipc.invoke('backup-restore'),
  createFolder: name => ipc.invoke('create-folder', name),
  renameFolder: (id, name) => ipc.invoke('rename-folder', id, name),
  toggleFolder: id => ipc.invoke('toggle-folder', id),
  deleteFolder: id => ipc.invoke('delete-folder', id),
  moveNote: (id, folderId) => ipc.invoke('move-note', id, folderId),
  arrangeNotes: entries => ipc.invoke('arrange-notes', entries),
  popOut: (id, x, y) => ipc.invoke('pop-out', id, x, y),
  reorder: ids => ipc.send('reorder', ids),
  openLink: url => ipc.send('open-link', url),
  dock: id => ipc.invoke('dock', id),
  del: id => ipc.invoke('delete-note', id),
  set: (k, v) => ipc.send('set-setting', k, v),
  dragStart: () => ipc.send('drag-start'),
  dragEnd: () => ipc.send('drag-end'),
  hide: () => ipc.send('hide'),
  quit: () => ipc.send('quit'),
  onRefresh: cb => ipc.on('refresh', cb)
});
